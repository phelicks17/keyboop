import Foundation

/// ЦИФРОВОЕ УСИЛЕНИЕ ВХОДА СВЕРХ 100% (просьба автора 25.10.2026).
///
/// Системный уровень входа (`MicVolume`) упирается в 100%: выше ползунка macOS не бывает. Если и на
/// максимуме микрофон тихий (далеко стоит, тихий голос, слабый Bluetooth), остаётся одно: умножить
/// записанный звук сами. Это не делает запись лучше, новых подробностей в ней не появляется, и шум
/// растёт ровно во столько же раз, что и голос. Помогает другое: распознавание и наши пороги тишины
/// работают с абсолютным уровнем, и слишком тихая запись для них похожа на молчание.
///
/// Потолок 400% (+12 дБ). Выше этого у обычного микрофона шум комнаты становится слышен наравне с
/// речью, а нормальная речь почти целиком уходит в ограничитель, то есть дальше крутить незачем.
///
/// Пики не обрезаем ступенькой, а мягко прижимаем: до 0.8 сигнал идёт как есть, выше плавно
/// подходит к 1 по tanh. Жёсткий срез на 1.0 давал бы на громких слогах хрип, который модели
/// распознают хуже, чем просто тихий звук.
enum InputBoost {
    static let maxPercent = 400
    private static let knee: Float = 0.8

    /// Умножить буфер на `gain` (1 — ничего не делать) с мягким ограничением пиков.
    static func apply(_ x: inout [Float], gain: Float) {
        guard gain != 1 else { return }
        for i in x.indices {
            let v = x[i] * gain
            let a = abs(v)
            if a > knee {
                let soft = knee + (1 - knee) * tanh((a - knee) / (1 - knee))
                x[i] = v < 0 ? -soft : soft
            } else {
                x[i] = v
            }
        }
    }
}
